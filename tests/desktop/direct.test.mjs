import { test } from 'node:test';
import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import http from 'node:http';
import { mkdtemp, rm } from 'node:fs/promises';
import { createDirectGrants } from '../../src/desktop/direct-grants.mjs';
import { challengeFor, parseConnectURL } from '../../src/desktop/connect-grants.mjs';
import { createDesktopHost } from '../../src/desktop/host.mjs';
import { DIRECT_PORTS } from '../../src/runtime/service-instance.mjs';
const origin='https://app.ltpass.com', other='https://app1.ltpass.com', random=()=>randomBytes(32).toString('base64url');
const fixture=()=>{const verifier=random();return{verifier,request:{origin,state:random(),challenge:challengeFor(verifier),callback:origin+'/agent/connect-callback.html',browser:'default',transport:'direct'}}};
const link=request=>'km-agent://connect?'+new URLSearchParams(request);
test('直连授权绑定来源、实例和 PKCE，单次领取，恢复有限时且可撤销',()=>{
 let now=0;const grants=createDirectGrants({now:()=>now}),f=fixture(),instanceId='instance';
 assert.equal(parseConnectURL(link(f.request),[origin]).transport,'direct');
 assert.throws(()=>parseConnectURL(link(f.request)+'&transport=direct',[origin]));
 assert.throws(()=>parseConnectURL(link({...f.request,transport:'anything'}),[origin]));
 assert.deepEqual(grants.issue(f.request,{instanceId}),{transport:'direct'});
 const claim={state:f.request.state,verifier:f.verifier,origin,instanceId};
 for(const patch of[{origin:other},{instanceId:'other'},{verifier:random()}])assert.throws(()=>grants.claim({...claim,...patch}));
 assert.equal(grants.claim({...claim,state:random()}),null);
 const token=grants.claim(claim).reconnectToken;assert.throws(()=>grants.claim(claim));
 // Reexecuting a copied request must not reopen a spent challenge.
 grants.issue(f.request,{instanceId});assert.throws(()=>grants.claim(claim));
 const resume={reconnectToken:token,origin,instanceId};
 grants.attach(token,'client-1');assert.equal(grants.resume(resume).previousClient,'client-1');
 for(const patch of[{origin:other},{instanceId:'other'},{reconnectToken:random()}])assert.throws(()=>grants.resume({...resume,...patch}));
 assert.equal(grants.revoke(resume),'client-1');assert.throws(()=>grants.resume(resume));
 const late=fixture();grants.issue(late.request,{instanceId});const lateToken=grants.claim({state:late.request.state,verifier:late.verifier,origin,instanceId}).reconnectToken;
 now=8*3600e3;assert.throws(()=>grants.resume({...resume,reconnectToken:lateToken}));
});
test('直连 HTTP: 发现不含凭据，错误来源/Host 拒绝，恢复替换旧客户端但不继承绑定',{timeout:15000},async t=>{
 const directory=await mkdtemp('/private/tmp/km-direct-http-');
 const adapter={health:async()=>({ready:true,version:'test'}),listSessions:async()=>[],close:async()=>{}};
 const host=createDesktopHost({directory,direct:true,codexEnabled:false,adapterFactory:()=>adapter});
 t.after(async()=>{await host.stop();await rm(directory,{recursive:true,force:true});});
 const started=await host.start({origins:[origin,other]}), endpoint=started.endpoint;
 assert.ok(DIRECT_PORTS.includes(Number(new URL(endpoint).port)));
 const call=(path,body,options={})=>fetch(endpoint+path,{method:body===undefined?'GET':'POST',headers:{Origin:origin,'Content-Type':'application/json','X-Km-Agent':'1',...options.headers},...(body===undefined?{}:{body:JSON.stringify(body)}),...options});
 const discovery=await call('/v1/connect/discover'),meta=(await discovery.json()).data;
 assert.equal(discovery.headers.get('access-control-allow-origin'),origin);
 assert.deepEqual(Object.keys(meta).sort(),['endpoint','instanceId','service','transport']);
 assert.equal((await call('/v1/connect/discover',undefined,{headers:{Origin:'https://evil.test'}})).status,403);
 const wrongHost=await new Promise((resolve,reject)=>{const req=http.get(endpoint+'/v1/connect/discover',{headers:{Origin:origin,Host:'evil.test'}},res=>{res.resume();resolve(res.statusCode)});req.on('error',reject)});assert.equal(wrongHost,403);
 const preflight=await call('/v1/connect/claim',undefined,{method:'OPTIONS',headers:{Origin:origin,'Access-Control-Request-Method':'POST','Access-Control-Request-Headers':'content-type,x-km-agent'}});assert.equal(preflight.status,204);
 const f=fixture(),body={state:f.request.state,verifier:f.verifier,instanceId:started.instanceId};
 assert.equal((await call('/v1/connect/claim',body)).status,202);
 assert.deepEqual(host.authorize(host.inspectLink(link(f.request)).id),{transport:'direct'});
 assert.equal((await call('/v1/connect/claim',{...body,verifier:random()})).status,403);
 assert.equal((await call('/v1/connect/claim',body,{headers:{Origin:other,'Content-Type':'application/json','X-Km-Agent':'1'}})).status,403);
 const result=await(await call('/v1/connect/claim',body)).json();assert.equal(result.ok,true);assert.equal(result.data.snapshot.binding,null);
 assert.equal((await call('/v1/connect/claim',body)).status,403);
 const old=result.data.token,resume={reconnectToken:result.data.reconnectToken,instanceId:started.instanceId};
 const snapshot=token=>call('/v1/snapshot',undefined,{headers:{Origin:origin,'X-Km-Agent':'1',Authorization:'Bearer '+token}});
 assert.equal((await snapshot(old)).status,200);
 assert.equal((await call('/v1/snapshot',undefined,{headers:{Origin:other,Authorization:'Bearer '+old}})).status,401);
 assert.equal((await call('/v1/local/publish',{}, {headers:{Origin:origin,Authorization:'Bearer '+old,'Content-Type':'application/json'}})).status,403);
 let latest;
 for(let i=0;i<14;i++){const restored=await(await call('/v1/connect/direct-resume',resume)).json();assert.equal(restored.ok,true);assert.equal(restored.data.snapshot.binding,null);latest=restored.data.token;}
 assert.equal((await snapshot(old)).status,401);assert.equal((await snapshot(latest)).status,200);
 assert.equal((await call('/v1/connect/direct-revoke',resume)).status,200);assert.equal((await snapshot(latest)).status,401);
 assert.equal((await call('/v1/connect/direct-resume',resume)).status,403);
});
