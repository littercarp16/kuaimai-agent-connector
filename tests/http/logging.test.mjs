import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm, readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { once } from 'node:events';
import { setTimeout as delay } from 'node:timers/promises';
import { createConnector } from '../../src/http/server.mjs';
import { createFileLogger } from '../../src/runtime/logger.mjs';

test('记录授权、SSE 断开、请求耗时和错误，且不泄漏请求内容或凭据', async t => {
  const directory = await mkdtemp('/private/tmp/km-http-log-'), path = join(directory,'service.log');
  const logger = createFileLogger({ path }), origin = 'http://127.0.0.1:4173';
  const adapter = { health: async () => ({ ready:true }), listSessions: async () => { throw Object.assign(Error('private-reply Bearer secret-token'), { code:'ECONNREFUSED' }); } };
  const bridge = createConnector({ adapter, allowedOrigins:[origin], autoTrust:{origin}, logger });
  bridge.server.listen(0,'127.0.0.1'); await once(bridge.server,'listening');
  t.after(async () => { await bridge.close(); logger.close(); await rm(directory,{recursive:true,force:true}); });
  const base = `http://127.0.0.1:${bridge.server.address().port}`;
  const call = (path, body, token) => fetch(base+path,{method:body===undefined?'GET':'POST',headers:{Origin:origin,'X-Km-Agent':'1','Content-Type':'application/json',...(token?{Authorization:'Bearer '+token}:{})},...(body===undefined?{}:{body:JSON.stringify(body)})});
  const handshake = await call('/v1/handshake',{}), authorized = await handshake.json();
  assert.equal(handshake.status,200,JSON.stringify(authorized)); const token = authorized.data.token;
  const controller = new AbortController();
  const stream = await fetch(base+'/v1/events',{headers:{Origin:origin,Authorization:'Bearer '+token},signal:controller.signal});
  const reader = stream.body.getReader(); await reader.read(); controller.abort(); await reader.cancel().catch(()=>{});
  assert.equal((await call('/v1/sessions',undefined,token)).status,500);
  assert.equal((await call('/v1/pair',{code:'private-prompt'},token)).status,403);
  assert.equal((await call('/private-path-secret?token=query-secret',undefined,token)).status,404);
  assert.equal((await call('/v1/disconnect',{},token)).status,200);
  await delay(30);
  const text = await readFile(path,'utf8'), records = text.trim().split('\n').map(JSON.parse);
  const connected = records.filter(r=>r.event==='client.connected'), disconnected = records.filter(r=>r.event==='client.disconnected');
  assert.equal(connected.length,1);assert.equal(disconnected.length,1);assert.equal(disconnected[0].clientId,connected[0].clientId);assert.equal(disconnected[0].reason,'requested');
  assert.equal(records.filter(r=>r.event==='stream.opened').length,1);assert.equal(records.filter(r=>r.event==='stream.closed').length,1);
  const requests=records.filter(r=>r.event==='http.request');assert.equal(requests.length,6);assert.equal(new Set(requests.map(r=>r.requestId)).size,6);
  assert.ok(requests.every(r=>r.durationMs>=0));assert.ok(requests.some(r=>r.requestId===handshake.headers.get('x-km-request-id')));
  const failed=requests.find(r=>r.statusCode===500);assert.equal(failed.level,'error');assert.equal(failed.errorCode,'ECONNREFUSED');
  assert.equal(requests.find(r=>r.path==='/v1/events').outcome,'aborted');
  assert.ok(requests.some(r=>r.path==='/unknown'));
  for(const secret of [token,'private-prompt','private-reply','secret-token','query-secret','private-path-secret']) assert.ok(!text.includes(secret));
});
